// Los tipos de las tablas de PostgreSQL, generados desde las migraciones (ADR-018): abre una base
// PGlite en memoria, corre las migraciones de todos los módulos con el mismo `migrate` del servidor
// y deja, por cada esquema, el archivo de tipos de su módulo. Lo usa db-types.ts.
import { existsSync, readFileSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { generate, Logger, PostgresDialect } from 'kysely-codegen';
import { createModules } from './modules.ts';
import { inMemoryUrl, migrate, openDatabase } from './platform/storage/db.ts';

// Lo que la base no sabe y el código sí: los valores que puede tener una columna de texto.
const overrides = {
  columns: { 'device_link.pairings.paired_by': "'button' | 'sign-in'" },
};

// `bytea` llega como `Uint8Array` en PGlite y como `Buffer` (que lo extiende) en `pg`.
const typeMapping = { bytea: 'Uint8Array' };

const header = (schema: string) =>
  `// Las tablas del esquema \`${schema}\` como las dejan sus migraciones. Lo genera \`pnpm db:types\`\n` +
  '// (ADR-018) y `pnpm check` controla que esté al día: no se edita a mano.\n';

export const tableTypesPath = (module: string): string =>
  `src/server/modules/${module}/tables.generated.ts`;

// El texto de cada archivo de tipos, por su ruta.
export async function generateTableTypes(): Promise<Map<string, string>> {
  const schemas = createModules().modules.flatMap(({ name, schema }) =>
    schema ? [{ module: name, schema }] : [],
  );
  const db = await openDatabase<unknown>(inMemoryUrl);
  try {
    await migrate(
      db,
      schemas.map(({ schema }) => schema),
    );
    const files = new Map<string, string>();
    for (const { module, schema } of schemas) {
      const text = await generate({
        db,
        dialect: new PostgresDialect(),
        logger: new Logger('silent'),
        includePattern: `${schema.schema}.*`,
        excludePattern: `${schema.schema}.kysely_*`,
        overrides,
        typeMapping,
        outFile: null,
        skipAutogeneratedFileComment: true,
      });
      files.set(tableTypesPath(module), header(schema.schema) + text);
    }
    return files;
  } finally {
    await db.destroy();
  }
}

// Los archivos de tipos que faltan o no coinciden con lo que dejan las migraciones.
export async function findStaleTableTypes(root: string): Promise<string[]> {
  const files = await generateTableTypes();
  return [...files]
    .filter(
      ([path, text]) =>
        !existsSync(join(root, path)) || readFileSync(join(root, path), 'utf8') !== text,
    )
    .map(([path]) => `${path}: no coincide con las migraciones; corré pnpm db:types`);
}

export async function writeTableTypes(root: string): Promise<void> {
  const files = await generateTableTypes();
  for (const [path, text] of files) {
    await mkdir(dirname(join(root, path)), { recursive: true });
    await writeFile(join(root, path), text);
  }
}
